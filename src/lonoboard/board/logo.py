# ---------- the logo ----------

def logo(parts, gap=2):
    """Hand-drawn 8x10 glyphs -> pixel grid with an outside-only drop shadow."""
    glyphs = [(G[ch], ramp) for text, ramp in parts for ch in text.upper()]
    w = sum(len(g[0]) + gap for g, _ in glyphs) - gap + 1
    h = 11
    P = [[None] * w for _ in range(h + 1)]
    x = 0
    for g, ramp in glyphs:
        for y, row in enumerate(g):
            for i, c in enumerate(row):
                if c == '#':
                    P[y][x + i] = ('L', ramp, y)
        x += len(g[0]) + gap
    # flood-fill the background from the edges so closed counters (P, A, R...) stay unshaded
    outside = [[False] * w for _ in range(h + 1)]
    stack = [(0, i) for i in range(w)] + [(h, i) for i in range(w)] + [(y, 0) for y in range(h + 1)] + [(y, w - 1) for y in range(h + 1)]
    while stack:
        y, i = stack.pop()
        if 0 <= y <= h and 0 <= i < w and not outside[y][i] and P[y][i] is None:
            outside[y][i] = True
            stack += [(y + 1, i), (y - 1, i), (y, i + 1), (y, i - 1)]
    for y in range(h):
        for i in range(w - 1):
            if P[y][i] and P[y][i][0] == 'L' and P[y + 1][i + 1] is None and outside[y + 1][i + 1]:
                P[y + 1][i + 1] = ('S',)
    return w, h + 1, P


RAMPS = {'A': (PX_A, CELL_A), 'B': (PX_B, CELL_B), 'D': (PX_D, CELL_D)}


def draw_logo(s, x0, y0, px):
    w, h, P = px
    for cy in range(h // 2):
        for cx in range(w):
            t, b = P[cy * 2][cx], P[cy * 2 + 1][cx]
            if t is None and b is None:
                continue
            if t and b and t[0] == 'L' and b[0] == 'L' and t[1] == b[1]:
                ch, f, bg = RAMPS[t[1]][1][cy]            # fully lit cell: dithered blend
                s.put(x0 + cx, y0 + cy, ch, f, bg)
                continue
            # a lone lit pixel takes the dominant colour of its row's blend, so edges match the fill
            col = lambda p: SHADOW if p[0] == 'S' else RAMPS[p[1]][1][p[2] // 2][1]
            if t and b:
                s.put(x0 + cx, y0 + cy, '▀', col(t), col(b))
            elif t:
                s.put(x0 + cx, y0 + cy, '▀', col(t))
            else:
                s.put(x0 + cx, y0 + cy, '▄', col(b))
